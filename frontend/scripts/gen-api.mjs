// `npm run gen:api`: writes src/services/api-types.ts from ../contracts/openapi.yaml with openapi-typescript (#34).
// The output depends only on the yaml: no timestamps, always LF. The banner carries a hash of the yaml, so
// src/services/api-types.test.ts can tell when the contract changed and nobody regenerated.
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import openapiTS, { astToString } from 'openapi-typescript'

const contract = new URL('../../contracts/openapi.yaml', import.meta.url)
const output = new URL('../src/services/api-types.ts', import.meta.url)

const yaml = readFileSync(contract, 'utf8').replace(/\r\n/g, '\n')
const hash = createHash('sha256').update(yaml).digest('hex')
const body = astToString(await openapiTS(contract)).replace(/\r\n/g, '\n')

const banner = `// Generated by \`npm run gen:api\` from contracts/openapi.yaml. Do not edit.\n// contract sha256: ${hash}\n\n`
writeFileSync(output, banner + body)
console.log(`gen:api wrote src/services/api-types.ts (${hash.slice(0, 12)})`)
